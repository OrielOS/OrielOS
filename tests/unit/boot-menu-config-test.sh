#!/usr/bin/env bash
# Unit tests for image/system/usr/libexec/orielos/boot-menu-config, which brings OrielOS's sections
# of the boot menu's configuration up to date: an outdated section is replaced, a missing one is
# added in name order, bootupd's own sections stay as they are, and nothing is written when the
# file is up to date, wasn't written by bootupd, or the result has errors. It works on files in a
# scratch directory (ORIELOS_GRUB_CFG, ORIELOS_GRUB_STATIC) with a stand-in for grub2-script-check,
# so it needs no root or VM. Prints PASS/FAIL per case and exits 1 if any case fails.
#
# Usage: tests/unit/boot-menu-config-test.sh
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TOOL="$ROOT/image/system/usr/libexec/orielos/boot-menu-config"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
PASSED=0
FAILED=0
OUT=""
RC=0

pass() {
    printf 'PASS  %s\n' "$1"
    PASSED=$((PASSED + 1))
}

fail() {
    printf 'FAIL  %s\n' "$1"
    if [[ -n "${2:-}" ]]; then printf '%s\n' "$2" | sed 's/^/      /'; fi
    FAILED=$((FAILED + 1))
}

check() {
    local name="$1"
    shift
    if "$@"; then pass "$name"; else fail "$name" "exit $RC: $OUT"$'\n'"$(cat "$CFG" 2>/dev/null)"; fi
}

CFG="$WORK/grub2/grub.cfg"
STATIC="$WORK/static"

# A fresh scratch directory: a grub.cfg as bootupd writes it, with OrielOS's menu snippet as it was
# at installation, the image's newer snippets, and a grub2-script-check that fails on "BROKEN".
setup() {
    rm -rf "${WORK:?}/grub2" "${WORK:?}/static" "${WORK:?}/bin"
    mkdir -p "$WORK/grub2" "$STATIC/configs.d" "$WORK/bin"
    cat >"$WORK/bin/grub2-script-check" <<'SH'
#!/usr/bin/env bash
! grep -q BROKEN "$1"
SH
    chmod +x "$WORK/bin/grub2-script-check"
    cat >"$CFG" <<'CFG'
# Generated by bootupd / do not edit

set timeout_style=menu
set timeout=1

# Other package code will be injected from here
### BEGIN 01_users.cfg ###
# Keep the comment for grub2-set-password
### BEGIN /etc/grub.d/01_users ###
if [ -f ${prefix}/user.cfg ]; then
  source ${prefix}/user.cfg
fi
### END /etc/grub.d/01_users ###
### END 01_users.cfg ###

### BEGIN 10_blscfg.cfg ###
blscfg
### END 10_blscfg.cfg ###

### BEGIN 12_orielos-menu.cfg ###
set timeout_style=hidden
load_env -f "${orielos_env}" orielos_boot_ok orielos_trial orielos_fails
### END 12_orielos-menu.cfg ###

### BEGIN 30_uefi-firmware.cfg ###
fwsetup --is-supported
### END 30_uefi-firmware.cfg ###
CFG
    # shellcheck disable=SC2016 # GRUB's variables, written as they are
    printf 'set timeout_style=hidden\nload_env -f "${orielos_env}" orielos_boot_ok orielos_trial orielos_fails orielos_menu\n' >"$STATIC/configs.d/12_orielos-menu.cfg"
    printf 'menuentry "Windows" {\n  chainloader /EFI/Microsoft/Boot/bootmgfw.efi\n}\n' >"$STATIC/configs.d/13_orielos-windows.cfg"
    printf 'blscfg\n' >"$STATIC/configs.d/10_blscfg.cfg"
    printf 'something else\n' >"$STATIC/configs.d/30_uefi-firmware.cfg"
    cp "$CFG" "$WORK/before"
}

run() {
    RC=0
    OUT="$(PATH="$WORK/bin:$PATH" ORIELOS_GRUB_CFG="$CFG" ORIELOS_GRUB_STATIC="$STATIC" "$TOOL" "$@" 2>&1)" || RC=$?
}

# The lines between a section's markers: section <name>
section() {
    sed -n "/^### BEGIN $1 ###\$/,/^### END $1 ###\$/p" "$CFG" | sed '1d;$d'
}

# The file's section names in order.
order() {
    sed -n 's/^### BEGIN \([^ /]*\.cfg\) ###$/\1/p' "$CFG" | paste -sd ' ' -
}

setup
run
check "an update brings the outdated OrielOS section in" test "$RC" -eq 0 -a "$(section 12_orielos-menu.cfg)" == "$(cat "$STATIC/configs.d/12_orielos-menu.cfg")"
check "and adds the missing one" test "$(section 13_orielos-windows.cfg)" == "$(cat "$STATIC/configs.d/13_orielos-windows.cfg")"
check "in name order, after the menu and before the firmware entry" test "$(order)" == "01_users.cfg 10_blscfg.cfg 12_orielos-menu.cfg 13_orielos-windows.cfg 30_uefi-firmware.cfg"
check "bootupd's own sections are left as they were, even where the image's differ" test "$(section 30_uefi-firmware.cfg)" == "fwsetup --is-supported"
check "sections nested in a snippet stay put" grep -qxF '### END /etc/grub.d/01_users ###' "$CFG"
check "and everything before the sections is untouched" test "$(head -n6 "$CFG")" == "$(head -n6 "$WORK/before")"
check "it says what it brought up to date" grep -q '12_orielos-menu.cfg 13_orielos-windows.cfg' <<<"$OUT"
check "no temporary file is left behind" test "$(find "$WORK/grub2" -type f | wc -l)" -eq 1

cp "$CFG" "$WORK/after"
touch -d '2026-01-01' "$CFG"
run
check "a second run changes nothing" cmp -s "$CFG" "$WORK/after"
check "and doesn't write the file again" test "$(date -r "$CFG" +%Y)" == 2026 -a "$(date -r "$CFG" +%m%d)" == 0101
chmod a-w "$WORK/grub2"
run
check "nor needs its folder to be writable" test "$RC" -eq 0
chmod u+w "$WORK/grub2"

setup
rm "$STATIC/configs.d/13_orielos-windows.cfg"
printf 'menuentry "Windows" {\n' >"$STATIC/configs.d/99_orielos-last.cfg"
run
check "a missing section that sorts after all the others goes at the end" test "$(order)" == "01_users.cfg 10_blscfg.cfg 12_orielos-menu.cfg 30_uefi-firmware.cfg 99_orielos-last.cfg"
check "after a blank line" test "$(tail -n4 "$CFG" | head -n1)" == ""

setup
printf 'BROKEN\n' >>"$STATIC/configs.d/12_orielos-menu.cfg"
run
check "a result with errors is refused" test "$RC" -eq 1
check "and the file stays as it was" cmp -s "$CFG" "$WORK/before"
check "with no temporary file left behind" test "$(find "$WORK/grub2" -type f | wc -l)" -eq 1

setup
sed -i '1d' "$CFG"
cp "$CFG" "$WORK/before"
run
check "a file bootupd didn't write is left alone" test "$RC" -eq 0
check "and isn't changed" cmp -s "$CFG" "$WORK/before"

setup
rm "$CFG"
run
check "no file at all is fine too" test "$RC" -eq 0 -a ! -e "$CFG"

setup
rm "$STATIC/configs.d/"*orielos*
run
check "an image without OrielOS snippets changes nothing" cmp -s "$CFG" "$WORK/before"

setup
run extra
check "an argument is refused with exit 2" test "$RC" -eq 2

printf '%d passed, %d failed\n' "$PASSED" "$FAILED"
[[ "$FAILED" -eq 0 ]]
